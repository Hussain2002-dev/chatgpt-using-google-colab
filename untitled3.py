# Install:  !pip install groq

import json
import os
import webbrowser
from getpass import getpass
from urllib.parse import quote_plus

from groq import Groq

GROQ_API_KEY = os.getenv("YOUR_GROQ_API_KEY_HERE") or getpass("Groq API key: ")
MODEL = "openai/gpt-oss-120b"
UNIVERSITY_PORTAL = "https://www.nu.edu.pk/"

client = Groq(api_key=GROQ_API_KEY)


def show_link(url: str) -> None:
    """Laptop par browser kholta hai, notebook me clickable link dikhata hai."""
    webbrowser.open(url)
    try:
        from IPython.display import HTML, display
        display(HTML(f'<a href="{url}" target="_blank">Yahan click karen: {url}</a>'))
    except ImportError:
        pass


# ---------- TASKS (tools) ----------
def youtube_search(query: str) -> str:
    show_link(f"https://www.youtube.com/results?search_query={quote_plus(query)}")
    return f"YouTube par '{query}' search kar diya."


def open_website(url: str) -> str:
    show_link(url)
    return f"{url} khol diya."


TOOLS_REGISTRY = {
    "youtube_search": youtube_search,
    "open_website": open_website,
}

TOOLS_SCHEMA = [
    {
        "type": "function",
        "function": {
            "name": "youtube_search",
            "description": "Open YouTube and search for a video, channel or topic.",
            "parameters": {
                "type": "object",
                "properties": {
                    "query": {"type": "string", "description": "Search text, e.g. 'Haider TV latest video'"}
                },
                "required": ["query"],
            },
        },
    },
    {
        "type": "function",
        "function": {
            "name": "open_website",
            "description": "Open a website using its full URL.",
            "parameters": {
                "type": "object",
                "properties": {
                    "url": {"type": "string", "description": "Full URL starting with https://"}
                },
                "required": ["url"],
            },
        },
    },
]

SYSTEM_PROMPT = f"""You are a helpful assistant. The user may write in Roman Urdu, Hindi or English.
Always choose the best tool for the request.
Known links:
- University portal: {UNIVERSITY_PORTAL}
If the user wants to watch or search something on YouTube, call youtube_search with a clean query.
If the user wants to open a site or portal, call open_website."""


# ---------- MAIN FUNCTION ----------
def run_assistant(user_prompt: str) -> str:
    response = client.chat.completions.create(
        model=MODEL,
        messages=[
            {"role": "system", "content": SYSTEM_PROMPT},
            {"role": "user", "content": user_prompt},
        ],
        tools=TOOLS_SCHEMA,
        tool_choice="auto",
    )

    message = response.choices[0].message
    results = []

    for call in message.tool_calls or []:
        func = TOOLS_REGISTRY[call.function.name]
        args = json.loads(call.function.arguments)
        results.append(func(**args))

    return "\n".join(results) or (message.content or "Samajh nahi aya.")


if __name__ == "__main__":
    while True:
        prompt = input("\nAap (exit likh kar band karen): ")
        if prompt.lower() in ("exit", "quit"):
            break
        print("AI:", run_assistant(prompt))